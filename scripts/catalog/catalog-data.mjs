//
// Row shape (positional, via P()):
//   brand, name, gender(M|W|U), family|null, launchYear|null, perfumer|null,
//   top, heart, base   (comma-separated -> arrays at import time)
//   accords            (comma-separated -> array)
//   description, sizes ("50ml=60000, 100ml=95000"), options
//
// options: { slug, concentration, draft }
//   slug          explicit slug where the brand-prefix rule would read badly
//   concentration stock-list concentration (EDP / EDT / Parfum ...), stored
//                 separately so it never pollutes the fragrance name
//   draft         imported hidden + flagged for owner verification
//
// Deliberate handling (see the implementation report):
//   - "Perfumer: Not separately listed" -> null (never a placeholder string)
//   - Symphony's supplied pyramid repeats the same three notes in every tier;
//     stored once as top notes rather than triplicated
//   - Dreams: fragrance data came unverified -> imported as a draft

